import { chromium, expect } from '@playwright/test'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const env = Object.fromEntries((await readFile(path.join(root, 'backend/.env'), 'utf8')).split(/\r?\n/).filter(line => line.includes('=') && !line.startsWith('#')).map(line => { const i = line.indexOf('='); return [line.slice(0, i), line.slice(i+1)] }))
const origin = process.env.E2E_ORIGIN || 'http://127.0.0.1:3000'
const screenshotDir = path.join(root, 'docs/screenshots')
await mkdir(screenshotDir, { recursive: true })
const browser = await chromium.launch({ channel: process.env.E2E_BROWSER_CHANNEL || 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1366, height: 900 } })
const errors = [], requests = []
page.on('pageerror', e => errors.push(e.message))
page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) requests.push({ method: request.method(), url: request.url() }) })
const results = []
async function check(name, task) { await task(); results.push({ name, status: '通过' }); console.log('PASS ' + name) }
async function screenshot(name) {
  await expect(page.locator('.el-message')).toHaveCount(0, { timeout: 10000 })
  await expect(page.locator('.el-select-dropdown:visible')).toHaveCount(0)
  await page.screenshot({ path: path.join(screenshotDir, name), fullPage: true })
}
async function select(label, option, container = page) {
  const field = container.locator('.el-form-item').filter({ has: page.locator('.el-form-item__label', { hasText: label }) }).first()
  await field.locator('.el-select').click()
  await page.locator('.el-select-dropdown__item:visible').filter({ hasText: option }).first().click()
}
async function login() {
  await page.getByLabel('用户名', { exact: true }).fill(env.INITIAL_ADMIN_USERNAME)
  await page.getByLabel('密码', { exact: true }).fill(env.INITIAL_ADMIN_PASSWORD)
  await page.getByRole('button', { name: '登录平台' }).click()
  await expect(page.getByRole('heading', { name: '工作看板' })).toBeVisible()
}
try {
  await check('代理与 SPA', async () => {
    expect((await page.request.get(origin + '/health')).status()).toBe(200)
    const unauthorized = await page.request.get(origin + '/api/employees')
    expect(unauthorized.status()).toBe(401)
    expect((await unauthorized.json()).error.code).toBe('UNAUTHORIZED')
    expect((await page.request.get(origin + '/employees/1')).status()).toBe(200)
  })
  await page.goto(origin)
  await screenshot('01-login.png')
  await check('登录与工作看板', login)
  await screenshot('02-dashboard.png')
  await page.getByRole('link', { name: '02 员工档案' }).click()
  const employeeNo = 'UI_' + Date.now().toString().slice(-10)
  await check('新增员工与部门岗位联动', async () => {
    await page.getByRole('button', { name: '新增员工' }).click()
    const dialog = page.locator('.el-overlay-dialog:visible')
    await dialog.getByLabel('工号', { exact: true }).fill(employeeNo)
    await dialog.getByLabel('姓名', { exact: true }).fill('演示自动化员工')
    await select('部门', '木工部（演示）', dialog)
    await select('主要岗位', '制琴工（演示）', dialog)
    await dialog.getByPlaceholder('选择入职日期').fill('2026-10-01')
    await dialog.getByLabel('姓名', { exact: true }).click()
    await dialog.getByRole('button', { name: '保存档案' }).click()
    await expect(dialog).not.toBeVisible()
    await expect(page.getByText(employeeNo, { exact: true })).toBeVisible()
  })
  await check('编辑员工并读取详情', async () => {
    const row = page.getByRole('row').filter({ hasText: employeeNo })
    await row.getByRole('button', { name: '编辑', exact: true }).click()
    const dialog = page.locator('.el-overlay-dialog:visible')
    await dialog.getByLabel('姓名', { exact: true }).fill('演示自动化员工改名')
    await dialog.getByRole('button', { name: '保存档案' }).click()
    await expect(dialog).not.toBeVisible()
    await row.getByRole('button', { name: '详情', exact: true }).click()
    await expect(page.getByRole('heading', { name: '演示自动化员工改名' })).toBeVisible()
  })
  await check('分配两项技能与调整熟练度', async () => {
    for (const name of ['琴体成型', '打磨抛光']) {
      await select('添加技能', name)
      await page.getByRole('button', { name: '添加技能', exact: true }).click()
      await expect(page.getByRole('cell', { name, exact: true })).toBeVisible()
    }
    const skillRow = page.getByRole('row').filter({ hasText: '琴体成型' })
    await skillRow.locator('.el-select').click()
    await page.locator('.el-select-dropdown__item:visible').filter({ hasText: '精通' }).click()
    await expect(skillRow).toContainText('精通')
    const polishRow = page.getByRole('row').filter({ hasText: '打磨抛光' })
    await polishRow.getByRole('button', { name: '解除关联' }).click()
    await page.getByRole('button', { name: '确定', exact: true }).click()
    await expect(polishRow).not.toBeVisible()
    await select('添加技能', '打磨抛光')
    await page.getByRole('button', { name: '添加技能', exact: true }).click()
    await expect(polishRow).toBeVisible()
  })
  await screenshot('03-employee-skills.png')
  await check('组合技能筛选', async () => {
    await page.getByRole('link', { name: '02 员工档案' }).click()
    await page.getByPlaceholder('姓名 / 工号').fill(employeeNo)
    await select('技能', '琴体成型')
    await page.getByRole('button', { name: '查询', exact: true }).click()
    await expect(page.getByRole('row').filter({ hasText: employeeNo })).toBeVisible()
  })
  await screenshot('04-employees.png')
  await check('离职归档与状态筛选', async () => {
    await page.getByRole('row').filter({ hasText: employeeNo }).getByRole('button', { name: '归档', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: '离职归档确认', exact: true })
    await dialog.getByPlaceholder('选择离职日期').fill('2026-10-26')
    await dialog.getByText('确认将', { exact: false }).click()
    await dialog.getByRole('button', { name: '确认归档', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await expect(page.getByRole('row').filter({ hasText: employeeNo })).not.toBeVisible()
    await select('状态', '离职')
    await page.getByRole('button', { name: '查询', exact: true }).click()
    await expect(page.getByRole('row').filter({ hasText: employeeNo })).toBeVisible()
  })
  await check('字典页面与新增编辑停用', async () => {
    await page.getByRole('link', { name: '03 部门管理' }).click()
    await page.getByRole('button', { name: '新增部门' }).click()
    const dialog = page.locator('.el-overlay-dialog:visible')
    await dialog.getByLabel('编码', { exact: true }).fill(employeeNo)
    await dialog.getByLabel('部门名称', { exact: true }).fill('演示UI部门' + employeeNo)
    await dialog.getByRole('button', { name: '保存', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    const row = page.getByRole('row').filter({ hasText: employeeNo })
    await row.getByRole('button', { name: '编辑', exact: true }).click()
    await dialog.getByLabel('部门名称', { exact: true }).fill('演示UI修改' + employeeNo)
    await dialog.getByRole('button', { name: '保存', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await row.getByRole('button', { name: '停用', exact: true }).click()
    await page.getByRole('button', { name: '确定', exact: true }).click()
    await expect(row.getByRole('button', { name: '启用', exact: true })).toBeVisible()
    await row.getByRole('button', { name: '查看岗位' }).click()
    await expect(page.getByRole('heading', { name: '岗位管理' })).toBeVisible()
    await page.getByRole('link', { name: '05 制琴技能' }).click()
    await expect(page.getByRole('heading', { name: '技能管理' })).toBeVisible()
    for (const [nav, label] of [['04 岗位管理', '岗位'], ['05 制琴技能', '技能']]) {
      await page.getByRole('link', { name: nav }).click()
      await page.getByRole('button', { name: '新增' + label }).click()
      const editDialog = page.locator('.el-overlay-dialog:visible')
      await editDialog.getByLabel('编码', { exact: true }).fill(employeeNo)
      await editDialog.getByLabel(label + '名称', { exact: true }).fill('演示UI' + label + employeeNo)
      if (label === '岗位') await select('所属部门', '木工部（演示）', editDialog)
      await editDialog.getByRole('button', { name: '保存', exact: true }).click()
      await expect(editDialog).not.toBeVisible()
      const createdRow = page.getByRole('row').filter({ hasText: employeeNo })
      await createdRow.getByRole('button', { name: '编辑', exact: true }).click()
      await editDialog.getByLabel(label + '名称', { exact: true }).fill('演示UI改名' + label + employeeNo)
      await editDialog.getByRole('button', { name: '保存', exact: true }).click()
      await expect(editDialog).not.toBeVisible()
      await createdRow.getByRole('button', { name: '停用', exact: true }).click()
      await page.getByRole('button', { name: '确定', exact: true }).click()
      await expect(createdRow.getByRole('button', { name: '启用', exact: true })).toBeVisible()
    }
  })
  await check('笔记本布局与同源请求', async () => {
    await page.setViewportSize({ width: 1280, height: 800 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    expect(requests.length).toBeGreaterThan(10)
    expect(requests.every(r => new URL(r.url).origin === origin)).toBe(true)
    expect(await page.evaluate(() => Object.keys(localStorage))).toEqual([])
    expect(await page.evaluate(() => Object.keys(sessionStorage))).toEqual([])
    expect(errors).toEqual([])
  })
  await check('深层路由刷新后重新登录与404', async () => {
    await page.reload()
    await expect(page.getByRole('heading', { name: '管理员登录' })).toBeVisible()
    await login()
    // SPA navigation keeps the in-memory login state.
    await page.evaluate(() => { history.pushState({}, '', '/unknown-page'); window.dispatchEvent(new PopStateEvent('popstate')) })
    await expect(page.getByText('404 · 页面不存在')).toBeVisible()
    await page.getByRole('button', { name: '返回首页' }).click()
    await page.getByRole('button', { name: '退出登录' }).click()
    await page.getByRole('button', { name: '确定', exact: true }).click()
    await expect(page.getByRole('heading', { name: '管理员登录' })).toBeVisible()
  })
  await writeFile(path.join(root, 'docs/e2e-results.json'), JSON.stringify({ results, apiRequests: requests, pageErrors: errors }, null, 2))
} catch (error) {
  await page.screenshot({ path: path.join(screenshotDir, 'failure.png'), fullPage: true })
  console.error(error.message)
  process.exitCode = 1
} finally { await browser.close() }
